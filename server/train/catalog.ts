/* ---------- Расширение словаря ----------
 * Модель должна переносить название из фразы, а не вспоминать одно из заученных: при словаре в три десятка дел
 * она учится выбирать из списка и на незнакомом («квиз», «зайти в Озон») подставляет знакомое. Поэтому слов много,
 * а часть дел собирается из глагола и дополнения. Слова для проверки на незнакомом — отдельно, в catalog-test.ts.
 */

const up = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
/** «именительный|винительный» — дела-существительные («тренировка|тренировку») и дела-глаголы («помыть машину») */
export const nouns = (list: string[]): TaskWord[] =>
  list.map((x) => {
    const [nom = '', acc = nom] = x.split('|');
    return { title: up(nom), add: nom, acc };
  });
/** Глагол и дополнения: «купить» + «хлеб». В правках говорят и целиком («перенеси купить хлеб»), и одним дополнением */
export const verbs = (verb: string, objects: string[], shortAcc = true): TaskWord[] =>
  objects.map((o, i) => ({ title: up(`${verb} ${o}`), add: `${verb} ${o}`, acc: shortAcc && i % 2 ? o : `${verb} ${o}` }));
/** «к терапевту|Терапевт|терапевта» */
export const visits = (list: string[]): TaskWord[] =>
  list.map((x) => {
    const [add = '', title = '', acc = ''] = x.split('|');
    return { title, add, acc };
  });
/** «Название|как говорят» */
export const films = (kind: Kind, list: string[]): Film[] =>
  list.map((x) => {
    const [title = '', acc = title] = x.split('|');
    return { title, acc, kind };
  });
/** «как говорят|Название|детали» */
export const wishes = (list: string[]): WishWord[] =>
  list.map((x) => {
    const [say = '', title = '', note = ''] = x.split('|');
    return { say, title: title || up(say), note };
  });
/** «Имя|кому|кем|кого» */
export const people = (list: string[]): Person[] =>
  list.map((x) => {
    const [nom = '', dat = '', ins = '', gen = ''] = x.split('|');
    return { nom, dat, ins, gen };
  });

