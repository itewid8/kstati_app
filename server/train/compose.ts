/* ---------- сборка с проверкой ---------- */

/** Собрать и проверить, что слов проверки нет; не вышло за 30 попыток — null (берётся слово из готового словаря) */
function safe<T>(make: () => T, texts: (x: T) => string[]): T | null {
  for (let i = 0; i < 30; i++) {
    const x = make();
    if (allowed(...texts(x))) return x;
  }
  return null;
}

export const compose = (d: Dice) => ({
  task: () => safe(() => task(d), (x) => [x.title, x.add, x.acc]),
  film: () => safe(() => film(d), (x) => [x.title, x.acc]),
  wish: () => safe(() => wish(d), (x) => [x.say, x.title]),
  idea: () => safe(() => idea(d), (x) => [x]),
  list: () => {
    const l = safe(() => list(d), (x) => [x[0]]);
    return l ? ([l[0], l[1], l[2].filter((i) => allowed(i))] as [string, string, string[]]) : null;
  },
  listTopic: () => safe(() => listTopic(d), (x) => [x.title, ...(x.list ?? [])]),
  newItem: () => safe(() => newItem(d), (x) => [x[0]]),
});
