function film(d: Dice): Film {
  const kind = d.pick(KINDS);
  const way = d.pick(['adj', 'adj', 'of', 'of', 'name', 'noun'] as const);
  if (way === 'name') {
    // Несклоняемое выдуманное имя: «Морлани», «Nova»
    const title = madeUp(d, d.pick(['о', 'и', 'у', 'э', '']));
    return { title, acc: title, kind };
  }
  if (way === 'noun') {
    const n = d.pick(FILM_NOUNS);
    return { title: up(n.nom), acc: up(n.acc), kind };
  }
  if (way === 'adj') {
    const n = d.pick(FILM_NOUNS);
    const a = d.pick(FILM_ADJ);
    return { title: up(`${adj(a, n.g)} ${n.nom}`), acc: up(`${adj(a, n.g, true, n.animate)} ${n.acc}`), kind };
  }
  const [head = '', headAcc = head] = d.pick(FILM_HEADS).split('|');
  const n = d.pick(FILM_NOUNS.filter((x) => x.gen));
  const tail = `${d.chance(0.5) ? `${d.pick(FILM_ADJ)}ого ` : ''}${n.gen}`;
  return { title: up(`${head} ${tail}`), acc: up(`${headAcc} ${tail}`), kind };
}

