function thing(d: Dice, acc: boolean): { say: string; nom: string } {
  const n = d.pick(THINGS);
  const a = d.chance(0.45) ? d.pick(QUALITY) : '';
  const nom = `${a ? `${adj(a, n.g)} ` : ''}${n.nom}`;
  return { say: acc ? `${a ? `${adj(a, n.g, true)} ` : ''}${n.acc}` : nom, nom };
}

function task(d: Dice): TaskWord {
  const way = d.pick(['verb', 'verb', 'verb', 'call', 'visit', 'event', 'event', 'shop', 'service', 'place'] as const);
  if (way === 'verb') {
    const [verb, extra] = d.pick(VERBS);
    const obj = thing(d, true).say;
    const tail = extra && d.chance(0.4) ? ` ${d.pick(extra === 'whom' ? TO_WHOM : WHERE_TO)}` : '';
    const add = `${verb} ${obj}${tail}`;
    return { title: up(add), add, acc: d.chance(0.5) ? add : obj };
  }
  if (way === 'call') {
    const add = `${d.pick(['позвонить', 'написать', 'напомнить', 'ответить', 'перезвонить'])} ${d.pick(ROLES_DAT)}${d.chance(0.5) ? ` ${d.pick(ABOUT)}` : ''}`;
    return { title: up(add), add, acc: add };
  }
  if (way === 'visit') {
    if (d.chance(0.15)) {
      const [add = '', title = '', acc = ''] = d.pick(SPECIALISTS_ADJ).split('|');
      return { title, add, acc };
    }
    const s = d.pick(SPECIALISTS);
    return { title: up(s), add: `к ${s}у`, acc: `${s}а` };
  }
  if (way === 'event') {
    const [nom = '', acc = nom] = d.pick(EVENTS).split('|');
    const tail = d.pick(EVENT_TAILS);
    return { title: up(`${nom} ${tail}`), add: `${nom} ${tail}`, acc: `${acc} ${tail}` };
  }
  if (way === 'shop') {
    const add = `${d.pick(['зайти', 'заехать', 'сходить', 'съездить', 'заскочить'])} ${d.pick(SHOPS)}`;
    return { title: up(add), add, acc: add };
  }
  if (way === 'service') {
    const add = d.chance(0.3) ? `созвон ${d.pick(APPS)}` : `${d.pick(['оплатить', 'продлить', 'отменить', 'подключить', 'проверить'])} ${d.pick(SERVICES)}`;
    return { title: up(add), add, acc: add };
  }
  const place = d.pick(PLACES);
  const name = madeUp(d);
  return { title: up(`${place} ${name}`), add: `${place} ${name}`, acc: `${PLACES_ACC[place] ?? place} ${name}` };
}

