const up = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const low = (s: string) => s.toLowerCase().replace(/ё/g, 'е');

/* ---------- слова проверки — под запретом ---------- */

const stemsOf = (s: string) => (low(s).match(/[а-яa-z]{4,}/g) ?? []).map((w) => w.slice(0, Math.max(4, w.length - 2)));
const strings = (v: unknown): string[] => (typeof v === 'string' ? [v] : Array.isArray(v) ? v.flatMap(strings) : v && typeof v === 'object' ? Object.values(v).flatMap(strings) : []);
const vocabStems = (m: Record<string, unknown>, skip: string[]) =>
  new Set(Object.entries(m).filter(([k, v]) => !skip.includes(k) && typeof v !== 'function').flatMap(([, v]) => strings(v)).flatMap(stemsOf));
// Имена людей и шум — общие по смыслу слова, их не сверяем
const SKIP = ['PEOPLE', 'MALE_A', 'NOISE', 'GROUPS'];
const known = vocabStems(base, SKIP);
const FORBID = new Set([...vocabStems(test, SKIP)].filter((s) => !known.has(s)));
/** В собранном нет слов из словаря проверки */
export const allowed = (...texts: string[]) => !texts.some((t) => stemsOf(t).some((s) => FORBID.has(s)));

